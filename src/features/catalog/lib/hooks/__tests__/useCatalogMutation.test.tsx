import { act, renderHook, waitFor } from "@testing-library/react";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { beforeEach, expect, it, vi } from "vitest";
import type { ReactNode } from "react";
import { useCatalogManager } from "../useCatalogManager";
const repo = vi.hoisted(() => ({ status: vi.fn(), versions: vi.fn(), operations: vi.fn(), operation: vi.fn(), mutate: vi.fn() }));
vi.mock("../../../api/catalog.repo.impl", () => ({ catalogRepo: repo }));
const status = { enabled: true, active_version: "v1", revision: "r1", active: null, limits: { max_file_size: 3145728 } };
const request = { kind: "delete" as const, base_version: "v1", expected_revision: "r1", target: { flow_id: "FLOW", catalog_item_id: "B1#01" } };
function wrapper({ children }: { children: ReactNode }) { return <QueryClientProvider client={new QueryClient({ defaultOptions: { queries: { retry: false } } })}>{children}</QueryClientProvider>; }
beforeEach(() => { vi.clearAllMocks(); sessionStorage.clear(); repo.status.mockResolvedValue(status); repo.versions.mockResolvedValue({ items: [] }); repo.operations.mockResolvedValue({ items: [] }); });
it("tracks CRUD with the existing pending identity and refreshes after completion", async () => {
  repo.mutate.mockImplementation(async input => ({ operation_id: input.operation_id, kind: "delete", status: "queued", message: "Queued" }));
  const { result } = renderHook(useCatalogManager, { wrapper });
  await waitFor(() => expect(result.current.canChange).toBe(true));
  await act(async () => { await result.current.mutate(request); });
  const id = result.current.pending!.id;
  expect(repo.mutate).toHaveBeenCalledWith({ ...request, operation_id: id });
  expect(result.current.canChange).toBe(false);
  repo.operation.mockResolvedValue({ operation_id: id, kind: "delete", status: "completed", message: "Deleted", version: "v2" });
  await act(async () => { await result.current.reconcile(); });
  expect(result.current.pending).toBeNull();
  expect(result.current.result?.version).toBe("v2");
  expect(repo.status).toHaveBeenCalledTimes(2);
});
it("recovers an uncertain CRUD request after remount and retries its original identity", async () => {
  repo.mutate.mockRejectedValue({ code: "NETWORK_ERROR", message: "Disconnected" });
  const first = renderHook(useCatalogManager, { wrapper });
  await waitFor(() => expect(first.result.current.canChange).toBe(true));
  await act(async () => { await first.result.current.mutate(request); });
  const id = first.result.current.pending!.id;
  first.unmount();
  const recovered = renderHook(useCatalogManager, { wrapper });
  await waitFor(() => expect(recovered.result.current.pending?.id).toBe(id));
  repo.operation.mockRejectedValue({ code: "NOT_FOUND", message: "No operation" });
  await act(async () => { await recovered.result.current.reconcile(); });
  expect(recovered.result.current.canRetry).toBe(true);
  act(() => recovered.result.current.requestRetry());
  repo.mutate.mockResolvedValue({ operation_id: id, kind: "delete", status: "queued", message: "Queued" });
  await act(async () => { await recovered.result.current.confirmRetry(); });
  expect(repo.mutate).toHaveBeenLastCalledWith({ ...request, operation_id: id });
});
it("keeps conflict results while refreshing the active revision and permits a new reviewed request", async () => {
  repo.status.mockResolvedValueOnce(status).mockResolvedValue({ ...status, active_version: "v2", revision: "r2" });
  repo.mutate.mockImplementation(async input => ({ operation_id: input.operation_id, kind: "delete", status: "conflict", message: "Catalog changed" }));
  const { result } = renderHook(useCatalogManager, { wrapper });
  await waitFor(() => expect(result.current.canChange).toBe(true));
  await act(async () => { await result.current.mutate(request); });
  expect(result.current.pending).toBeNull();
  expect(result.current.result?.status).toBe("conflict");
  expect(result.current.error).toBe("Catalog changed");
  expect(result.current.status?.revision).toBe("r2");
  const previousId = result.current.result?.operation_id;
  await act(async () => { await result.current.mutate({ ...request, base_version: "v2", expected_revision: "r2" }); });
  expect(repo.mutate.mock.calls[1][0]).toMatchObject({ base_version: "v2", expected_revision: "r2" });
  expect(repo.mutate.mock.calls[1][0].operation_id).not.toBe(previousId);
});
it("recovers server-side running CRUD operations even without session storage", async () => {
  repo.operations.mockResolvedValue({ items: [{ operation_id: "server-op", kind: "update", status: "running", message: "Writing", processed_items: 25, total_items: 1843 }] });
  const { result } = renderHook(useCatalogManager, { wrapper });
  await waitFor(() => expect(result.current.pending?.id).toBe("server-op"));
  expect(result.current.result?.processed_items).toBe(25);
  expect(result.current.canChange).toBe(false);
  expect(result.current.recoveryAvailable).toBe(false);
  repo.operation.mockResolvedValue({ operation_id: "server-op", kind: "update", status: "completed", message: "Saved", version: "v2" });
  await act(async () => { await result.current.reconcile(); });
  expect(result.current.pending).toBeNull();
  expect(result.current.result?.status).toBe("completed");
});
